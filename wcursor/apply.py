"""Apply a cursor theme and size consistently across the whole desktop.

There is no single place that controls the X11 cursor on a niri + DMS system,
so this module updates every consumer we know about:

======================  ====================================================
Target                  What is written
======================  ====================================================
DMS                     ``~/.config/DankMaterialShell/settings.json``
                        (``cursorSettings.theme`` / ``.size``) and the
                        companion ``~/.config/niri/dms/cursor.kdl``
X11 / Xresources        ``~/.Xresources`` (``Xcursor.theme`` / ``.size``)
X11 default theme       ``~/.icons/default/index.theme`` (``Inherits=``)
GTK 3 / GTK 4           ``settings.ini`` (``gtk-cursor-theme-name`` / ``-size``)
GSettings               ``org.gnome.desktop.interface cursor-theme`` / ``-size``
niri                    reload the compositor config so it picks up ``cursor.kdl``
======================  ====================================================

DMS keeps its settings in memory and rewrites ``settings.json`` on exit, and its
``settings set`` IPC call rejects ``cursorSettings``, so the only reliable path
is: stop DMS, edit the file, start DMS again.  Every mutated file is backed up
once to ``<file>.wcursor-bak``.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Tuple

HOME = Path.home()
CONFIG = Path(os.environ.get("XDG_CONFIG_HOME") or (HOME / ".config"))

DMS_SETTINGS = CONFIG / "DankMaterialShell" / "settings.json"
DMS_CURSOR_KDL = CONFIG / "niri" / "dms" / "cursor.kdl"
XRDB = HOME / ".Xresources"
ICONS_DEFAULT = HOME / ".icons" / "default" / "index.theme"
GTK3 = CONFIG / "gtk-3.0" / "settings.ini"
GTK4 = CONFIG / "gtk-4.0" / "settings.ini"

BACKUP_SUFFIX = ".wcursor-bak"

DMS_CURSOR_KDL_TEMPLATE = (
    "// ! DO NOT EDIT !\n"
    "// ! AUTO-GENERATED BY DMS !\n"
    "// ! CHANGES WILL BE OVERWRITTEN !\n"
    "// ! PLACE YOUR CUSTOM CONFIGURATION ELSEWHERE !\n"
    "\n"
    "cursor {\n"
    '    xcursor-theme "{theme}"\n'
    "    xcursor-size {size}\n"
    "}"
)


@dataclass
class Step:
    target: str
    status: str          # updated | unchanged | would update | skipped | error
    detail: str = ""

    def __str__(self) -> str:
        return f"{self.target}: {self.status}" + (f" ({self.detail})" if self.detail else "")


@dataclass
class Location:
    name: str
    theme: Optional[str]
    size: Optional[int]


# --- tiny file helpers -------------------------------------------------------

def _read_text(path: Path) -> Optional[str]:
    try:
        return path.read_text()
    except (OSError, UnicodeDecodeError):
        return None


def _read_json(path: Path):
    text = _read_text(path)
    if text is None:
        return None
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        return None


def _backup(path: Path) -> None:
    backup = path.with_name(path.name + BACKUP_SUFFIX)
    if path.is_file() and not backup.exists():
        shutil.copy2(path, backup)


def _write_text(path: Path, text: str, dry_run: bool) -> None:
    if dry_run:
        return
    _backup(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def _set_ini_key(text: str, key: str, value: str) -> str:
    pattern = re.compile(rf"^(\s*{re.escape(key)}\s*=).*$", re.MULTILINE)
    if pattern.search(text):
        return pattern.sub(lambda m: m.group(1) + value, text, count=1)
    sep = "" if text.endswith("\n") or not text else "\n"
    return f"{text}{sep}{key}={value}\n"


def _set_colon_key(text: str, key: str, value: str) -> str:
    pattern = re.compile(rf"^(\s*{re.escape(key)}\s*:).*$", re.MULTILINE)
    if pattern.search(text):
        return pattern.sub(lambda m: m.group(1) + " " + value, text, count=1)
    sep = "" if text.endswith("\n") or not text else "\n"
    return f"{text}{sep}{key}: {value}\n"


# --- external process helpers ------------------------------------------------

def _run(args, timeout=20):
    try:
        return subprocess.run(args, capture_output=True, text=True, timeout=timeout)
    except (OSError, subprocess.SubprocessError):
        return None


def _systemctl(*args, timeout=30):
    if not shutil.which("systemctl"):
        return None
    return _run(["systemctl", "--user", *args], timeout=timeout)


def _pgrep_dms() -> bool:
    result = _run(["pgrep", "-x", "dms"], timeout=5)
    return bool(result and result.returncode == 0 and result.stdout.strip())


def dms_running() -> bool:
    result = _systemctl("is-active", "dms.service", timeout=5)
    if result is not None and result.stdout.strip() == "active":
        return True
    return _pgrep_dms()


def _stop_dms(timeout: float = 15.0) -> bool:
    if _systemctl("stop", "dms.service") is None and shutil.which("dms"):
        _run(["dms", "kill"], timeout=15)
    deadline = time.time() + timeout
    while time.time() < deadline:
        if not dms_running():
            return True
        time.sleep(0.3)
    return not dms_running()


def _start_dms() -> bool:
    return _systemctl("start", "dms.service") is not None


def reload_niri() -> Step:
    if not shutil.which("niri"):
        return Step("niri", "skipped", "niri not installed")
    result = _run(["niri", "msg", "action", "load-config-file"], timeout=15)
    if result is None:
        return Step("niri", "skipped", "niri is not running")
    if result.returncode == 0:
        return Step("niri", "updated", "config reloaded")
    return Step("niri", "error", (result.stderr or result.stdout).strip())


# --- individual targets ------------------------------------------------------

def _apply_dms_settings(theme: str, size: int, dry_run: bool) -> Step:
    data = _read_json(DMS_SETTINGS)
    if data is None:
        return Step("dms settings.json", "skipped", "settings.json not found")
    cursor = data.get("cursorSettings")
    if not isinstance(cursor, dict):
        cursor = {}
        data["cursorSettings"] = cursor
    if cursor.get("theme") == theme and cursor.get("size") == size:
        return Step("dms settings.json", "unchanged", f"{theme}/{size}")
    cursor["theme"] = theme
    cursor["size"] = int(size)
    _write_text(DMS_SETTINGS, json.dumps(data, indent=2, ensure_ascii=False), dry_run)
    return Step("dms settings.json", "would update" if dry_run else "updated", f"{theme}/{size}")


def _apply_dms_cursor_kdl(theme: str, size: int, dry_run: bool) -> Step:
    text = DMS_CURSOR_KDL_TEMPLATE.replace("{theme}", theme).replace("{size}", str(int(size)))
    if _read_text(DMS_CURSOR_KDL) == text:
        return Step("dms cursor.kdl", "unchanged", f"{theme}/{size}")
    _write_text(DMS_CURSOR_KDL, text, dry_run)
    return Step("dms cursor.kdl", "would update" if dry_run else "updated", f"{theme}/{size}")


def _apply_xresources(theme: str, size: int, dry_run: bool) -> Step:
    if not XRDB.exists() and dry_run:
        return Step(".Xresources", "would update", f"{theme}/{size}")
    text = _read_text(XRDB) or ""
    new = _set_colon_key(_set_colon_key(text, "Xcursor.theme", theme), "Xcursor.size", str(int(size)))
    if new == text:
        return Step(".Xresources", "unchanged", f"{theme}/{size}")
    _write_text(XRDB, new, dry_run)
    return Step(".Xresources", "would update" if dry_run else "updated", f"{theme}/{size}")


def _apply_icons_default(theme: str, dry_run: bool) -> Step:
    text = _read_text(ICONS_DEFAULT)
    if text is None:
        text = "[Icon Theme]\nName=Default\nComment=Default Cursor Theme\n"
    new = _set_ini_key(text, "Inherits", theme)
    if new == text:
        return Step(".icons/default", "unchanged", theme)
    _write_text(ICONS_DEFAULT, new, dry_run)
    return Step(".icons/default", "would update" if dry_run else "updated", theme)


def _apply_gtk(path: Path, theme: str, size: int, dry_run: bool) -> Step:
    label = f"gtk-{path.parent.name.split('-')[-1]}"
    text = _read_text(path)
    if text is None:
        text = "[Settings]\n"
    new = _set_ini_key(text, "gtk-cursor-theme-name", theme)
    new = _set_ini_key(new, "gtk-cursor-theme-size", str(int(size)))
    if new == text:
        return Step(label, "unchanged", f"{theme}/{size}")
    _write_text(path, new, dry_run)
    return Step(label, "would update" if dry_run else "updated", f"{theme}/{size}")


def _gsettings_schema_ok() -> bool:
    result = _run(["gsettings", "get", "org.gnome.desktop.interface", "cursor-theme"], timeout=10)
    return bool(result and result.returncode == 0)


def _apply_gsettings(theme: str, size: int, dry_run: bool) -> Step:
    if not shutil.which("gsettings") or not _gsettings_schema_ok():
        return Step("gsettings", "skipped", "schema not available")
    existing = _read_gsettings()
    if existing == (theme, int(size)):
        return Step("gsettings", "unchanged", f"{theme}/{size}")
    if dry_run:
        return Step("gsettings", "would update", f"{theme}/{size}")
    _run(["gsettings", "set", "org.gnome.desktop.interface", "cursor-theme", theme])
    _run(["gsettings", "set", "org.gnome.desktop.interface", "cursor-size", str(int(size))])
    return Step("gsettings", "updated", f"{theme}/{size}")


# --- orchestration -----------------------------------------------------------

def apply_cursor(
    theme: str,
    size: int,
    *,
    dms: bool = True,
    xresources: bool = True,
    icons_default: bool = True,
    gtk: bool = True,
    gsettings: bool = True,
    niri: bool = True,
    dry_run: bool = False,
    restart_dms: bool = True,
) -> List[Step]:
    """Push ``theme``/``size`` everywhere.  Returns the list of per-target steps."""
    steps: List[Step] = []
    size = int(size)

    # DMS first: restarting it rewrites some of the files below.
    if dms:
        were_running = dms_running()
        if were_running and not dry_run and restart_dms:
            if not _stop_dms():
                steps.append(Step("dms", "error", "could not stop DMS; not changed"))
            else:
                steps.append(_apply_dms_settings(theme, size, False))
                steps.append(_apply_dms_cursor_kdl(theme, size, False))
                if _start_dms():
                    steps.append(Step("dms", "restarted", ""))
                else:
                    steps.append(Step("dms", "error", "could not start DMS"))
        elif dry_run:
            steps.append(_apply_dms_settings(theme, size, True))
            steps.append(_apply_dms_cursor_kdl(theme, size, True))
        else:
            # DMS not running: safe to edit its files directly.
            steps.append(_apply_dms_settings(theme, size, False))
            steps.append(_apply_dms_cursor_kdl(theme, size, False))

    if xresources:
        steps.append(_apply_xresources(theme, size, dry_run))
    if icons_default:
        steps.append(_apply_icons_default(theme, dry_run))
    if gtk:
        steps.append(_apply_gtk(GTK3, theme, size, dry_run))
        steps.append(_apply_gtk(GTK4, theme, size, dry_run))
    if gsettings:
        steps.append(_apply_gsettings(theme, size, dry_run))
    if niri and not dry_run:
        steps.append(reload_niri())
    return steps


# --- readers -----------------------------------------------------------------

def _read_gsettings() -> Optional[Tuple[str, int]]:
    if not shutil.which("gsettings"):
        return None
    theme = _run(["gsettings", "get", "org.gnome.desktop.interface", "cursor-theme"], timeout=10)
    size = _run(["gsettings", "get", "org.gnome.desktop.interface", "cursor-size"], timeout=10)
    if not theme or not size or theme.returncode or size.returncode:
        return None
    return theme.stdout.strip().strip("'"), _safe_int(size.stdout.strip())


def _safe_int(value: str) -> Optional[int]:
    try:
        return int(str(value).strip().strip("'"))
    except (TypeError, ValueError):
        return None


def _read_ini_key(text: Optional[str], key: str) -> Optional[str]:
    if not text:
        return None
    match = re.search(rf"^\s*{re.escape(key)}\s*=\s*(.+?)\s*$", text, re.MULTILINE)
    return match.group(1) if match else None


def _read_colon_key(text: Optional[str], key: str) -> Optional[str]:
    if not text:
        return None
    match = re.search(rf"^\s*{re.escape(key)}\s*:\s*(.+?)\s*$", text, re.MULTILINE)
    return match.group(1) if match else None


def _dms_live_cursor() -> Optional[Tuple[str, int]]:
    if not shutil.which("dms") or not dms_running():
        return None
    result = _run(["dms", "ipc", "call", "settings", "get", "cursorSettings"], timeout=10)
    if not result or result.returncode:
        return None
    try:
        data = json.loads(result.stdout.strip())
    except json.JSONDecodeError:
        return None
    return data.get("theme"), data.get("size")


def current() -> List[Location]:
    """Every place a cursor theme/size is recorded, as read from disk."""
    locations: List[Location] = []

    data = _read_json(DMS_SETTINGS) or {}
    cursor = data.get("cursorSettings") or {}
    locations.append(Location("dms (settings.json)", cursor.get("theme"), _safe_int(cursor.get("size"))))

    live = _dms_live_cursor()
    if live:
        locations.append(Location("dms (live)", live[0], _safe_int(live[1])))

    kdl = _read_text(DMS_CURSOR_KDL) or ""
    kdl_theme = re.search(r'xcursor-theme\s+"([^"]+)"', kdl)
    kdl_size = re.search(r"xcursor-size\s+(\d+)", kdl)
    locations.append(Location(
        "dms cursor.kdl",
        kdl_theme.group(1) if kdl_theme else None,
        _safe_int(kdl_size.group(1)) if kdl_size else None,
    ))

    xres = _read_text(XRDB)
    locations.append(Location(
        ".Xresources",
        _read_colon_key(xres, "Xcursor.theme"),
        _safe_int(_read_colon_key(xres, "Xcursor.size") or ""),
    ))

    locations.append(Location(".icons/default", _read_ini_key(_read_text(ICONS_DEFAULT), "Inherits"), None))

    for path, label in ((GTK3, "gtk-3.0"), (GTK4, "gtk-4.0")):
        text = _read_text(path)
        locations.append(Location(
            label,
            _read_ini_key(text, "gtk-cursor-theme-name"),
            _safe_int(_read_ini_key(text, "gtk-cursor-theme-size") or ""),
        ))

    gs = _read_gsettings()
    locations.append(Location("gsettings", gs[0], gs[1] if gs else None))
    return locations
