"""Turn a :class:`wcursor.pack.Pack` into an installable Xcursor theme."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence

from . import icons, roles, xcursor
from .pack import Pack

#: Size ladder used when the caller does not ask for specific sizes.
DEFAULT_LADDER = (24, 32, 48, 64)
MAX_SIZE = 256
INDEX_THEME = """[Icon Theme]
Name={name}
Comment=Cursor theme generated by wcursor
Inherits=default
"""


class ThemeError(Exception):
    """Raised when a theme cannot be built."""


@dataclass
class BuiltCursor:
    canonical: str
    native: int
    frames: int
    sizes: List[int]


def parse_sizes(spec) -> Optional[List[int]]:
    """Parse ``"24,32,48"`` (or a list of ints) into a sorted size list."""
    if spec is None:
        return None
    if isinstance(spec, (list, tuple)):
        values = [int(v) for v in spec]
    else:
        values = [int(v) for v in str(spec).replace(";", ",").split(",") if v.strip()]
    if not values:
        return None
    for v in values:
        if not 0 < v <= MAX_SIZE:
            raise ThemeError(f"size out of range (1..{MAX_SIZE}): {v}")
    return sorted(set(values))


def resolve_sizes(requested: Optional[Sequence[int]], native: int) -> List[int]:
    if requested:
        return sorted(set(int(s) for s in requested))
    sizes = set(DEFAULT_LADDER)
    sizes.add(native)
    sizes.add(native * 2)
    return sorted(s for s in sizes if 0 < s <= MAX_SIZE)


def _frame_to_image(frame: icons.Frame, size: int, method: str) -> xcursor.Image:
    base = xcursor.Image(
        size=frame.width,
        width=frame.width,
        height=frame.height,
        xhot=frame.xhot,
        yhot=frame.yhot,
        delay=frame.delay,
        pixels=xcursor.premultiply(frame.rgba),
    )
    if size == frame.width and frame.width == frame.height:
        return base
    return xcursor.rescale(base, size, method)


def build(
    pack: Pack,
    out_dir,
    sizes: Optional[Iterable[int]] = None,
    method: str = "auto",
    name: Optional[str] = None,
    verbose: bool = False,
) -> Dict[str, BuiltCursor]:
    """Write ``out_dir`` as a complete Xcursor theme.  Returns per-cursor info."""
    out_dir = Path(out_dir)
    cursors_dir = out_dir / "cursors"
    cursors_dir.mkdir(parents=True, exist_ok=True)

    # A stale cursors/ dir would leave dangling aliases behind; start clean.
    for stale in cursors_dir.iterdir():
        if stale.is_file() or stale.is_symlink():
            stale.unlink()

    built: Dict[str, BuiltCursor] = {}
    sizes_spec = list(sizes) if sizes else None

    for canonical, src in sorted(pack.mapping.items()):
        try:
            frames = icons.load(src)
        except icons.CursorFormatError as exc:
            if verbose:
                print(f"  ! skipping {canonical}: {exc}")
            continue
        native = max(f.width for f in frames)
        targets = resolve_sizes(sizes_spec, native)
        if not targets:
            raise ThemeError(f"no sizes resolved for {canonical}")
        images: List[xcursor.Image] = []
        for size in targets:
            for frame in frames:
                images.append(_frame_to_image(frame, size, method))
        xcursor.write(cursors_dir / canonical, images)
        built[canonical] = BuiltCursor(canonical, native, len(frames), targets)
        if verbose:
            print(f"  + {canonical:<18} {native}px x{len(frames)} -> {targets}")

    if not built:
        raise ThemeError(f"nothing convertible in {pack.directory}")

    for canonical in built:
        for alias in roles.aliases_for(canonical):
            link = cursors_dir / alias
            if link.is_symlink() or link.exists():
                link.unlink()
            link.symlink_to(canonical)

    theme_name = name or pack.name
    (out_dir / "index.theme").write_text(INDEX_THEME.format(name=theme_name))
    return built


def read_theme_sizes(theme_dir) -> List[int]:
    """Union of the nominal sizes across every cursor file in a theme."""
    cursors_dir = Path(theme_dir) / "cursors"
    sizes = set()
    if cursors_dir.is_dir():
        for p in cursors_dir.iterdir():
            if p.is_file() and not p.is_symlink():
                try:
                    sizes.update(xcursor.probe(p))
                except xcursor.XcursorError:
                    continue
    return sorted(sizes)


def group_by_size(images: Iterable[xcursor.Image]) -> Dict[int, List[xcursor.Image]]:
    """``{nominal size: [frames in order]}``."""
    groups: Dict[int, List[xcursor.Image]] = {}
    for image in images:
        groups.setdefault(image.size, []).append(image)
    return groups


def choose_source_size(available: Sequence[int], target: int) -> int:
    """Best existing size to derive ``target`` from.

    Prefers the largest size that does not exceed the target (so a 48px is
    built from a 32px, not a 24px), otherwise falls back to the smallest one.
    """
    lower = [s for s in available if s <= target]
    return max(lower) if lower else min(available)


def add_sizes(
    theme_dir,
    sizes: Iterable[int],
    method: str = "auto",
    from_size: Optional[int] = None,
    dry_run: bool = False,
    verbose: bool = False,
) -> Dict[str, List[int]]:
    """Ensure every cursor in ``theme_dir`` contains ``sizes``.

    Missing sizes are generated from the best existing one (see
    :func:`choose_source_size`), frame-by-frame, so animations keep playing.
    Returns ``{cursor name: final sizes}``.
    """
    cursors_dir = Path(theme_dir) / "cursors"
    if not cursors_dir.is_dir():
        raise ThemeError(f"{theme_dir} is not a cursor theme")
    requested = sorted({int(s) for s in sizes})
    for s in requested:
        if not 0 < s <= MAX_SIZE:
            raise ThemeError(f"size out of range (1..{MAX_SIZE}): {s}")

    result: Dict[str, List[int]] = {}
    for path in sorted(cursors_dir.iterdir()):
        if path.is_symlink() or not path.is_file():
            continue
        try:
            images = xcursor.read(path)
        except xcursor.XcursorError:
            continue
        groups = group_by_size(images)
        existing = sorted(groups)
        final = sorted(set(existing) | set(requested))
        result[path.name] = final
        if final == existing:
            continue
        new_images: List[xcursor.Image] = []
        for target in requested:
            if target in groups:
                continue
            source_size = from_size if from_size in groups else choose_source_size(existing, target)
            for frame in groups[source_size]:
                new_images.append(xcursor.rescale(frame, target, method))
        combined = images + new_images
        combined.sort(key=lambda im: im.size)
        if not dry_run:
            xcursor.write(path, combined)
        if verbose:
            verb = "would add" if dry_run else "added"
            print(f"  {verb} {path.name:<18} {existing} -> {final}")
    return result
